/**
 * Resolve the /Branding hero's featured brand worlds from the real asset
 * library and write src/data/brandingFeatured.js.
 *
 *   node scripts/branding-featured.mjs
 *
 * The hero shows one brand across five touchpoints. Rather than hand-listing
 * paths (which drifted before - three brands in the design mock had no assets
 * at all), each slot is resolved from a candidate list and every candidate is
 * checked against public/ before it is written. A slot with no file on disk is
 * omitted, so the hero can only ever render images that exist.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRANDS, getBrandAssetPath } from '../src/data/brands.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exists = (rel) => rel && fs.existsSync(path.join(ROOT, 'public', decodeURIComponent(rel).replace(/^\//, '')));

/** Brands that carry enough real work to stand as a complete brand world. */
const FEATURED = ['ashe', 'lacroix', 'boom-chica', 'honey', 'baron-herzog', 'pita-basta'];

/** Section titles differ per brand; match loosely, in priority order. */
const sectionImage = (brand, ...needles) => {
  for (const needle of needles) {
    const sec = (brand.sections || []).find((s) => s.title.toLowerCase().includes(needle));
    const hit = sec?.images?.find((im) => exists(getBrandAssetPath(brand, im)));
    if (hit) return getBrandAssetPath(brand, hit);
  }
  return '';
};

const firstExisting = (brand, ...files) => {
  for (const f of files) {
    const p = getBrandAssetPath(brand, f);
    if (exists(p)) return p;
  }
  return '';
};

const SLOTS = [
  ['world', 'Complete brand world', (b) => firstExisting(b, 'generated/master/brand-world-master.webp') || sectionImage(b, 'complete brand world')],
  ['product', 'Packaging', (b) => firstExisting(b, 'generated/packaging/packaging-lineup.webp') || sectionImage(b, 'packaging', 'product')],
  ['campaign', 'Campaign', (b) => firstExisting(b, 'generated/social/social-system.webp', 'generated/campaign/campaign-system.webp') || sectionImage(b, 'campaign')],
  ['digital', 'Digital', (b) => firstExisting(b, 'generated/web/homepage-hero.webp', 'generated/web/website-responsive.webp') || sectionImage(b, 'digital')],
  ['identity', 'Identity', (b) => sectionImage(b, 'brand identity', 'logo', 'identity') || firstExisting(b, b.logo || '')],
];

const byId = Object.fromEntries(BRANDS.map((b) => [b.id, b]));
const out = [];
for (const id of FEATURED) {
  const b = byId[id];
  if (!b) { console.warn(`skip ${id}: not in BRANDS`); continue; }
  const touchpoints = {};
  for (const [key, label, resolve] of SLOTS) {
    const src = resolve(b);
    if (src) touchpoints[key] = { src, label };
  }
  const missing = SLOTS.map(([k]) => k).filter((k) => !touchpoints[k]);
  out.push({
    id: b.id,
    name: b.name,
    subtitle: b.subtitle || '',
    category: b.category || '',
    accent: b.accent,
    tags: b.tags || [],
    href: `#brand-${b.id}`,
    touchpoints,
  });
  console.log(`${b.name.padEnd(20)} ${Object.keys(touchpoints).length}/5 slots` + (missing.length ? `   missing: ${missing.join(', ')}` : ''));
}

const file =
  `/* GENERATED by scripts/branding-featured.mjs - do not edit by hand.\n` +
  `   Every path below was verified to exist under public/ when generated.\n` +
  `   Re-run after adding brand assets: node scripts/branding-featured.mjs */\n\n` +
  `export const FEATURED_BRAND_WORLDS = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'src/data/brandingFeatured.js'), file);
console.log(`\nwrote src/data/brandingFeatured.js (${out.length} brand worlds)`);
